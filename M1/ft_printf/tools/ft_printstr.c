#include "ft_printf.h"

void	ft_printstr(char *s)
{
	size_t	i;

	i = 0;
	if (!s)
	{
		write(1, "(null)\n", 7);
		return ;
	}
	while (s[i] != '\0')
	{
		write(1, &s[i], 1);
		i++;
	}
	return ;
}
